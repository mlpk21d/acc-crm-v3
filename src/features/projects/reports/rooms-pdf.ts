import PDFDocument from "pdfkit";
import { drawRoomsTable, type RoomReportRow } from "./rooms-table";

export function roomsPdfFilename(projectName: string, date: Date): string {
  const name = projectName.normalize("NFKD").replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-zA-Z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 100) || "Project";
  return `${name}-Door-Styles-And-Finishes-${date.toISOString().slice(0, 10)}.pdf`;
}

export async function createRoomsPdf(projectName: string, rooms: readonly RoomReportRow[], date = new Date()): Promise<Buffer> {
  const doc = new PDFDocument({ size: "LETTER", margins: { top: 40, bottom: 55, left: 36, right: 36 }, bufferPages: true,
    info: { Title: `${projectName} | Door Styles and Finishes`, Author: "ACC CRM" } });
  const chunks: Buffer[] = [];
  const result = new Promise<Buffer>((resolve, reject) => {
    doc.on("data", chunk => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
  });
  const dateLabel = date.toLocaleDateString("en-US", { year: "numeric", month: "short", day: "numeric", timeZone: "UTC" });
  doc.font("Helvetica").fontSize(8).fillColor("#94a3b8").text(dateLabel, 36, 36, { width: 540, align: "right" });
  doc.font("Helvetica-Bold").fontSize(17).fillColor("#0f172a").text(projectName, 36, 55, { width: 540, continued: true });
  doc.font("Helvetica").fillColor("#475569").text(" | Door Styles and Finishes");
  const ruleY = doc.y + 15;
  doc.moveTo(36, ruleY).lineTo(576, ruleY).strokeColor("#0f172a").lineWidth(1).stroke();
  doc.lineWidth(0.4);
  drawRoomsTable(doc, rooms, ruleY + 16);
  const range = doc.bufferedPageRange();
  for (let index = range.start; index < range.start + range.count; index++) {
    doc.switchToPage(index);
    doc.moveTo(36, 748).lineTo(576, 748).strokeColor("#dbe3ee").stroke();
    // Footers occupy the reserved bottom margin without triggering a new page.
    const bottomMargin = doc.page.margins.bottom;
    doc.page.margins.bottom = 0;
    doc.font("Helvetica").fontSize(7).fillColor("#94a3b8")
      .text(`Generated by ACC CRM - ${dateLabel} | Page ${index + 1} of ${range.count}`, 36, 755,
        { width: 540, align: "center", lineBreak: false });
    doc.page.margins.bottom = bottomMargin;
  }
  doc.end();
  return result;
}
